bool CAtomEmulator::Initialize(unsigned nCoreId)
{
  m_nCoreId = nCoreId;

  m_Debugger.SetEmulator(this);
  m_Debugger.SetDebug(false);

  InitKeymap();
  InitMem();

  LoadROMs();

  m_ramrom_enable = true;
  m_main_ramflag = 5;
  m_RR_enables |= RAMROM_FLAG_DISKROM; // Forceer de DiskROM-vlag aan
  m_RR_bankreg = 0;

  SetRRPtrs();
  // CoreID opslaan
  m_Mmc.SetEmulator(this);
  CLogger::Get()->Write("emulator", LogNotice, "Core %u gekoppeld aan AtomMMC map: %s", nCoreId, s_CoreFolderNames[nCoreId]);
  m_Mmc.Initialize(s_CoreFolderNames[nCoreId]);

  m_Pia.Initialize();
  Reset();

  m_bInitialized = true;
  return true;
}

