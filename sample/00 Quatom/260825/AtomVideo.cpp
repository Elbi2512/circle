CAtomVideo::CAtomVideo(void)
    : m_Sy(0), m_Cy(0), m_Addr(0x8000)
{
    for (int i = 0; i < 256 * 192; i++)
    {
        m_VRAM[i] = 0;
    }
}

CAtomVideo::~CAtomVideo(void)
{
}

u32 CAtomVideo::GetColorARGB(u8 nPaletteIndex)
{
    if (nPaletteIndex > 8)
    {
        nPaletteIndex = 0;
    }
    return s_PaletteARGB[nPaletteIndex];
}

