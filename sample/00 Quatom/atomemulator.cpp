      m_pc++;
      m_x = ReadMem(addr);
      setzn(m_x);
      PollTime(3);
      break;

    case 0xB8: /* CLV */
      m_p.v = 0;
      PollTime(2);
      break;

    case 0xB9: /* LDA abs,y */
      addr = getw();
      PollTime(3);
      if ((addr & 0xFF00) ^ ((addr + m_y) & 0xFF00))
        PollTime(1);
      m_a = ReadMem(addr + m_y);
      setzn(m_a);
      PollTime(1);
      break;

    case 0xBA: /* TSX */
      m_x = m_s;
      setzn(m_x);
      PollTime(2);
      break;

    case 0xBC: /* LDY abs,x */
      addr = getw();
      if ((addr & 0xFF00) ^ ((addr + m_x) & 0xFF00))
        PollTime(1);
      m_y = ReadMem(addr + m_x);
      setzn(m_y);
      PollTime(4);
      break;

    case 0xBD: /* LDA abs,x */
      addr = getw();
      if ((addr & 0xFF00) ^ ((addr + m_x) & 0xFF00))
        PollTime(1);
      m_a = ReadMem(addr + m_x);
      setzn(m_a);
      PollTime(4);
      break;

    case 0xBE: /* LDX abs,y */
      addr = getw();
      if ((addr & 0xFF00) ^ ((addr + m_y) & 0xFF00))
        PollTime(1);
      m_x = ReadMem(addr + m_y);
      setzn(m_x);
      PollTime(4);
      break;

    case 0xC0: /* CPY imm */
      temp = ReadMem(m_pc);
      m_pc++;
      setzn((uint8_t)(m_y - temp));
      m_p.c = (m_y >= temp);
      PollTime(2);
      break;

    case 0xC1: /* CMP (,x) */
      temp = (ReadMem(m_pc) + m_x) & 0xFF;
      m_pc++;
      addr = ReadMem(temp) | (ReadMem((temp + 1) & 0xFF) << 8);
      temp = ReadMem(addr);
      setzn((uint8_t)(m_a - temp));
      m_p.c = (m_a >= temp);
      PollTime(6);
      break;

    case 0xC4: /* CPY zp */
      addr = ReadMem(m_pc);
      m_pc++;
      temp = ReadMem(addr);
      setzn((uint8_t)(m_y - temp));
      m_p.c = (m_y >= temp);
      PollTime(3);
      break;

    case 0xC5: /* CMP zp */
      addr = ReadMem(m_pc);
      m_pc++;
      temp = ReadMem(addr);
      setzn((uint8_t)(m_a - temp));
      m_p.c = (m_a >= temp);
      PollTime(3);
      break;

    case 0xC6: /* DEC zp */
      addr = ReadMem(m_pc);
      m_pc++;
      temp = (ReadMem(addr) - 1) & 0xFF;
      WriteMem(addr, temp);
      setzn(temp);
      PollTime(5);
      break;

    case 0xC8: /* INY */
      m_y = (m_y + 1) & 0xFF;
      setzn(m_y);
      PollTime(2);
      break;

    case 0xC9: /* CMP imm */
      temp = ReadMem(m_pc);
      m_pc++;
      setzn((uint8_t)(m_a - temp));
      m_p.c = (m_a >= temp);
      PollTime(2);
      break;

    case 0xCA: /* DEX */
      m_x = (m_x - 1) & 0xFF;
      setzn(m_x);
      PollTime(2);
      break;

    case 0xCC: /* CPY abs */
      addr = getw();
      temp = ReadMem(addr);
      setzn((uint8_t)(m_y - temp));
      m_p.c = (m_y >= temp);
      PollTime(4);
      break;

    case 0xCD: /* CMP abs */
      addr = getw();
      temp = ReadMem(addr);
      setzn((uint8_t)(m_a - temp));
      m_p.c = (m_a >= temp);
      PollTime(4);
      break;

    case 0xCE: /* DEC abs */
      addr = getw();
      PollTime(4);
      temp = (ReadMem(addr) - 1) & 0xFF;
      PollTime(1);
      WriteMem(addr, (temp + 1) & 0xFF);
      PollTime(1);
      WriteMem(addr, temp);
      setzn(temp);
      break;

    case 0xD0: /* BNE */
      offset = (int8_t)ReadMem(m_pc);
      m_pc++;
      temp = 2;
      if (!m_p.z)
      {
        temp++;
        if ((m_pc & 0xFF00) ^ ((m_pc + offset) & 0xFF00))
          temp++;
        m_pc += offset;
      }
      PollTime(temp);
      break;

    case 0xD1: /* CMP (),y */
      temp = ReadMem(m_pc);
      m_pc++;
      addr = ReadMem(temp) | (ReadMem((temp + 1) & 0xFF) << 8);
      if ((addr & 0xFF00) ^ ((addr + m_y) & 0xFF00))
        PollTime(1);
