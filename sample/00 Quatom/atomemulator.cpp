      m_p.c = (m_a >= temp);
      PollTime(5);
      break;

    case 0xD5: /* CMP zp,x */
      addr = (ReadMem(m_pc) + m_x) & 0xFF;
      m_pc++;
      temp = ReadMem(addr);
      setzn((uint8_t)(m_a - temp));
      m_p.c = (m_a >= temp);
      PollTime(3);
      break;

    case 0xD6: /* DEC zp,x */
      addr = (ReadMem(m_pc) + m_x) & 0xFF;
      m_pc++;
      temp = (ReadMem(addr) - 1) & 0xFF;
      WriteMem(addr, temp);
      setzn(temp);
      PollTime(5);
