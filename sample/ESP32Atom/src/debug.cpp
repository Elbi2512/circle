void debugdisassemble()
{
    uint16_t temp;
    char s[256];
    uint8_t op = dreadmem(debugdisaddr);
    uint8_t p1 = dreadmem(debugdisaddr + 1), p2 = dreadmem(debugdisaddr + 2);

    sprintf(s, "%04X : ", debugdisaddr);
    debugout(s);
    debugout(dopnamenmos[op]);
    //debugout(" ");
    switch (dopaddr[op])
    {
    case IMP:
        sprintf(s, "        ");
        debugout(s);
        break;
    case IMPA:
        sprintf(s, "A       ");
        debugout(s);
        break;
    case IMM:
        sprintf(s, "#%02X     ", p1);
        debugout(s);
        debugdisaddr++;
        break;
    case ZP:
        sprintf(s, "%02X      ", p1);
        debugout(s);
        debugdisaddr++;
        break;
    case ZPX:
        sprintf(s, "%02X,X    ", p1);
        debugout(s);
        debugdisaddr++;
        break;
    case ZPY:
        sprintf(s, "%02X,Y    ", p1);
        debugout(s);
        debugdisaddr++;
        break;
    case IND:
        sprintf(s, "(%02X)    ", p1);
        debugout(s);
        debugdisaddr++;
        break;
    case INDX:
        sprintf(s, "(%02X,X)  ", p1);
        debugout(s);
        debugdisaddr++;
        break;
    case INDY:
        sprintf(s, "(%02X),Y  ", p1);
        debugout(s);
        debugdisaddr++;
        break;
    case ABS:
        sprintf(s, "%02X%02X    ", p2, p1);
        debugout(s);
        debugdisaddr += 2;
        break;
    case ABSX:
        sprintf(s, "%02X%02X,X  ", p2, p1);
        debugout(s);
        debugdisaddr += 2;
        break;
    case ABSY:
        sprintf(s, "%02X%02X,Y  ", p2, p1);
        debugout(s);
        debugdisaddr += 2;
        break;
    case IND16:
        sprintf(s, "(%02X%02X)  ", p2, p1);
        debugout(s);
        debugdisaddr += 2;
        break;
    case IND1X:
        sprintf(s, "(%02X%02X,X)", p2, p1);
        debugout(s);
        debugdisaddr += 2;
        break;
    case BRA:
        temp = debugdisaddr + 2 + (signed char)p1;
        sprintf(s, "%04X    ", temp);
        debugout(s);
        debugdisaddr++;
        break;
    }
    debugdisaddr++;
    //        WriteConsole(consf,"\n",strlen("\n"),NULL,NULL);
}