void CTextConsole::WriteFormat(const char *pFormat, ...)
{
    if (pFormat == nullptr)
        return;

    va_list args;
    va_start(args, pFormat);

    CString str;
    str.FormatV(pFormat, args); // Circle's eigen bare-metal printf engine

    va_end(args);

    WriteString((const char *)str);
}

